// ─────────────────────────────────────────────────────────
// 组装成查表结构
// ─────────────────────────────────────────────────────────
export interface NoteSemantics {
  /** 体感温度：-1 冷 / 0 中性 / 1 暖。未标注词默认为 0。 */
  temp: -1 | 0 | 1;
  texture: Texture;
}

const TEMP_MAP = new Map<string, -1 | 0 | 1>();
for (const n of TEMP_COOL) TEMP_MAP.set(n, -1);
for (const n of TEMP_WARM) TEMP_MAP.set(n, 1);
// 显式登记中性：不写进来会被门禁判成漏标（漏标 = 静默退化，比标错更危险）
for (const n of TEMP_NEUTRAL) TEMP_MAP.set(n, 0);

const TEXTURE_MAP = new Map<string, Texture>();
for (const [tex, words] of Object.entries(TEXTURE) as [Texture, string[]][]) {
  for (const w of words) {
    // 后写入覆盖先写入：一个词只保留一个主质感（如「乳香」既在 resin 又在 smoke，取后者）
    TEXTURE_MAP.set(w, tex);
  }
}

/** 精确查表（供脚本/门禁使用）：未命中返回 null，不做兜底 */
export function lookupNoteSemantics(note: string): NoteSemantics | null {
  const key = note.trim();
  const hasTemp = TEMP_MAP.has(key);
  const hasTex = TEXTURE_MAP.has(key);
  if (!hasTemp && !hasTex) return null;
  return {
    temp: TEMP_MAP.get(key) ?? 0,
    texture: TEXTURE_MAP.get(key) ?? 'none',
  };
}

/** 查表（含兜底）：未命中的词归为中性，保证运行时永不抛错 */
export function noteSemantics(note: string): NoteSemantics {
  return lookupNoteSemantics(note) ?? { temp: 0, texture: 'none' };
}

