// ============================================================
// 香调词 → 语义属性（P2 离线语义层 · 静态知识表）
//
// 为什么需要这一层：
//   现有的 6 维雷达（花香/木质/清新/东方/柑橘/美食）只回答「是什么香调族」，
//   回答不了「摸起来什么质感、闻起来冷的还是暖的」。
//   实测（scripts/verify-coverage-window.ts）6 维余弦已经撞到天花板：
//   Top-1 相似度 0.96、Top-20 仍有 0.885 —— 再调权重也榨不出区分度。
//   要继续提精度只能换「表示」，本文件就是新的表示层。
//
// 为什么是静态表而不是运行时调 LLM：
//   · 零延迟、零成本、零外网依赖（移动端弱网可用）
//   · 可复现（同输入永远同结果），而 LLM 有温度、会漂移
//   · 可审计（有 audit-perfume-semantics.ts 门禁守着覆盖度与取值合法性）
//   「AI 的活」在离线生成阶段做完了，运行时只查表。
//
// 两个正交轴：
//   temp     体感冷暖（-1 冷 … +1 暖）—— 与季节、清爽/温暖诉求直接相关
//   texture  质感（13 类）—— 6 维雷达完全没覆盖的维度
// ============================================================

